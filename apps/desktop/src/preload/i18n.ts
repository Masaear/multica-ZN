function translateNode(node: Node): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const text = node.textContent?.trim();
    if (text && ZH_DICT[text]) {
      node.textContent = node.textContent!.replace(text, ZH_DICT[text]);
    }
  } else if (node.nodeType === Node.ELEMENT_NODE) {
    const el = node as Element;
    const tag = el.tagName;
    if (tag === "INPUT" || tag === "TEXTAREA" || tag === "SCRIPT" || tag === "STYLE") return;
    const inputEl = el as HTMLInputElement;
    if (inputEl.placeholder && ZH_DICT[inputEl.placeholder]) {
      inputEl.placeholder = ZH_DICT[inputEl.placeholder];
    }
    if (el.getAttribute("title") && ZH_DICT[el.getAttribute("title")!]) {
      el.setAttribute("title", ZH_DICT[el.getAttribute("title")!]);
    }
    if (el.getAttribute("aria-label") && ZH_DICT[el.getAttribute("aria-label")!]) {
      el.setAttribute("aria-label", ZH_DICT[el.getAttribute("aria-label")!]);
    }
    node.childNodes.forEach(translateNode);
  }
}

export function installZhCN(): void {
  if (typeof window === "undefined" || typeof document === "undefined") return;

  const run = () => {
    if (document.body) translateNode(document.body);
  };

  if (document.readyState === "loading") {
    window.addEventListener("DOMContentLoaded", run);
  } else {
    run();
  }

  const observer = new MutationObserver((mutations) => {
    mutations.forEach(({ addedNodes }) => {
      addedNodes.forEach(translateNode);
    });
  });

  const attach = () => {
    if (document.body) {
      observer.observe(document.body, { childList: true, subtree: true });
    }
  };

  if (document.body) {
    attach();
  } else {
    window.addEventListener("DOMContentLoaded", attach);
  }
}
